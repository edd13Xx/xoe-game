/** How often the simulated book refreshes (ms). One "tick" = one bucket of this size. */
export const BOOK_TICK_MS = 1500
/** Levels per side generated by the synthetic book. */
export const BOOK_DEPTH = 12

/** Small deterministic 32-bit hash -> [0, 1). Same inputs always give the same output. */
export function hashUnit(...parts: number[]): number {
  let h = 0x811c9dc5
  for (const p of parts) {
    let x = Math.floor(Number.isFinite(p) ? p : 0) | 0
    for (let k = 0; k < 4; k++) {
      h ^= x & 0xff
      h = Math.imul(h, 0x01000193)
      x >>>= 8
    }
  }
  h ^= h >>> 16
  h = Math.imul(h, 0x85ebca6b)
  h ^= h >>> 13
  h = Math.imul(h, 0xc2b2ae35)
  h ^= h >>> 16
  return (h >>> 0) / 4294967296
}

/** Price decimals for a given book step so neighbouring levels never round to the same price. */
export function bookDecimals(step: number): number {
  if (!(step > 0)) return 6
  let d = Math.min(8, Math.max(2, Math.ceil(-Math.log10(step)) + 1))
  // Also show enough decimals to represent the step itself (e.g. 0.000225 -> 6).
  while (d < 8 && Math.abs(Math.round(step * 10 ** d) - step * 10 ** d) > 1e-6) d += 1
  return d
}

/**
 * Seeded size for one book level, keyed only by its price (not its position), so a level keeps
 * its size as the mid drifts. Each level re-rolls on its own cadence (2–5 ticks, derived from its
 * price), so only a few rows change on any given tick, like a real book. ~1 in 9 rolls is a
 * larger "wall" (3x–6x).
 */
function levelSize(priceKey: number, sideKey: number, tick: number): number {
  const period = 2 + Math.floor(hashUnit(priceKey, sideKey, 7) * 4)
  const phase = Math.floor(hashUnit(priceKey, sideKey, 11) * period)
  const epoch = Math.floor((tick + phase) / period)
  const noise = hashUnit(priceKey, sideKey, epoch, 3)
  let size = 0.25 + noise * noise * 1.6
  if (hashUnit(priceKey, sideKey, epoch, 5) < 0.11) size *= 3 + hashUnit(priceKey, sideKey, epoch, 9) * 3
  return Math.max(0.01, +size.toFixed(4))
}

/**
 * Deterministic synthetic order book (testnet sim, no real money).
 * Same (mid, aggregation, tick) always returns the same book; best ask > best bid always.
 */
export function buildSyntheticBook(
  mid: number,
  aggregation = 0.01,
  tick = 0,
): { bids: BookLevel[]; asks: BookLevel[]; spread: number } {
  const safeMid = mid > 0 && Number.isFinite(mid) ? mid : 1
  let step = aggregation > 0 ? aggregation : safeMid * 0.0005
  // Keep every bid price above zero.
  step = Math.min(step, safeMid / (BOOK_DEPTH + 2))
  const dp = bookDecimals(step)
  const unit = 10 ** dp
  const bids: BookLevel[] = []
  const asks: BookLevel[] = []
  // Snap levels to the step grid around mid so the same price key keeps its identity as mid drifts.
  // Now and then the touch level on one side is momentarily empty, so the spread breathes (1–4 steps).
  const bidGap = hashUnit(tick, 31) < 0.2 ? 1 : 0
  const askGap = hashUnit(tick, 37) < 0.2 ? 1 : 0
  const bestBidIdx = Math.floor(safeMid / step - 1e-9) - bidGap
  const bestAskIdx = Math.max(bestBidIdx + 1, Math.ceil(safeMid / step + 1e-9)) + askGap
  for (let i = 0; i < BOOK_DEPTH; i++) {
    const bIdx = bestBidIdx - i
    const aIdx = bestAskIdx + i
    const bp = Math.round(bIdx * step * unit) / unit
    const ap = Math.round(aIdx * step * unit) / unit
    bids.push({ price: bp, size: levelSize(Math.round(bp * unit), 1, tick), side: "bid" })
    asks.push({ price: ap, size: levelSize(Math.round(ap * unit), 2, tick), side: "ask" })
  }
  const spread = +(asks[0]!.price - bids[0]!.price).toFixed(dp)
  return { bids, asks, spread }
}

/** Stable identity for a book level (side + price). */
export function bookLevelKey(l: Pick<BookLevel, "side" | "price">): string {
  return `${l.side}-${l.price}`
}

/** Book levels with running (cumulative) size from the best price outward. */
export function withCumulative(levels: readonly BookLevel[]): (BookLevel & { cum: number })[] {
  let cum = 0
  return levels.map((l) => {
    cum += l.size
    return { ...l, cum: +cum.toFixed(4) }
  })
}

/**
 * Simulated mid for a tick: smooth seeded drift that stays within about ±0.4% of the anchor,
 * so the desk feels live without wandering. Deterministic for tests.
 */
export function simMidAt(anchor: number, tick: number): number {
  const slow = Math.floor(tick / 6)
  const t = (tick % 6) / 6
  const a = hashUnit(slow, 17) - 0.5
  const b = hashUnit(slow + 1, 17) - 0.5
  const smooth = a + (b - a) * (t * t * (3 - 2 * t))
  const jitter = (hashUnit(tick, 23) - 0.5) * 0.15
  return anchor * (1 + (smooth + jitter) * 0.008)
}

/** Advance the paper desk to a tick: new sim mid and a fresh book. Orders/balances untouched. */
export function tickPaperDesk(state: PaperDeskState, tick: number): PaperDeskState {
  const anchor = state.anchor ?? state.mid
  const mid = +simMidAt(anchor, tick).toPrecision(6)
  const book = buildSyntheticBook(mid, state.aggregation, tick)
  const before = new Map<string, number>()
  for (const l of [...state.bids, ...state.asks]) before.set(bookLevelKey(l), l.size)
  const changed: string[] = []
  for (const l of [...book.bids, ...book.asks]) {
    const was = before.get(bookLevelKey(l))
    if (was != null && was !== l.size) changed.push(bookLevelKey(l))
  }
  return { ...state, anchor, mid, bids: book.bids, asks: book.asks, spread: book.spread, tick, changed }
}

export function estimateTotal(side: OrderSide, type: OrderType, price: number | null, size: number, mid: number): {
  total: number
  fee: number
  feeRate: number
} {
  const px = type === "market" || price == null ? mid : price
  const notional = Math.max(0, px * Math.max(0, size))
  const feeRate = type === "market" ? PAPER_FEE_TAKER : PAPER_FEE_MAKER
  const fee = notional * feeRate
  return { total: notional + (side === "buy" ? fee : 0), fee, feeRate }
}

let oid = 0
export function placePaperOrder(
  state: PaperDeskState,
  side: OrderSide,
  type: OrderType,
  price: number | null,
  size: number,
): { state: PaperDeskState; error?: string } {
  if (size <= 0) return { state, error: "Size must be > 0" }
  const est = estimateTotal(side, type, price, size, state.mid)
  if (side === "buy" && est.total > state.cash) return { state, error: "Not enough sim cash for that order." }
  if (side === "sell" && size > state.base) return { state, error: "Not enough coins to sell." }
  oid += 1
  const order: PaperOrder = {
    id: `po-${oid}`,
    pair: state.pair,
    side,
    type,
    price: type === "market" ? state.mid : price,
    size,
    status: type === "market" ? "filled" : "open",
    createdAt: Date.now(),
    fee: est.fee,
  }
  let cash = state.cash
  let base = state.base
  const fills = [...state.fills]
  const openOrders = [...state.openOrders]
  if (order.status === "filled") {
    order.filledAt = Date.now()
    if (side === "buy") {
      cash -= est.total
      base += size
    } else {
      cash += Math.max(0, (order.price ?? state.mid) * size - est.fee)
      base -= size
    }
    fills.unshift({
      id: `pf-${oid}`,
      orderId: order.id,
      pair: state.pair,
      side,
      price: order.price ?? state.mid,
      size,
      fee: est.fee,
      at: Date.now(),
    })
  } else {
    openOrders.unshift(order)
  }
  return { state: { ...state, cash, base, openOrders, fills: fills.slice(0, 40) } }
}

export function initialPaperDesk(pair: TickerPair = "XLM-USD", mid = 0.12): PaperDeskState {
  const aggregation = +(mid * 0.0005).toPrecision(2)
  const book = buildSyntheticBook(mid, aggregation, 0)
  const chart = Array.from({ length: 24 }, (_, i) => ({
    t: Date.now() - (23 - i) * 900_000,
    price: mid * (1 + Math.sin(i / 3) * 0.01),
  }))
  return {
    pair,
    mid,
    spread: book.spread,
    anchor: mid,
    tick: 0,
    aggregation,
    bids: book.bids,
    asks: book.asks,
    recentTrades: book.asks.slice(0, 6).map((a, i) => ({
      price: a.price,
      size: a.size,
      side: i % 2 === 0 ? "sell" : "buy",
      at: Date.now() - i * 4000,
    })),
    chart,
    openOrders: [],
    fills: [],
    cash: 10_000,
    base: 5000,
  }
}

